"""realms/game_creation/pipeline.py — REAL game project scaffolds.

Outputs (all real files on disk):
  · Godot 4 project — project.godot + main.tscn + main.gd + README
  · Blender script — operator can `blender --python <script.py>` to build
                       a procedural scene matching the spec
  · Game design doc — markdown with gameplay loop, mechanics, world
                       structure, progression, art direction, audio
                       direction, all derived from EnrichedIntent + spec

Reality Enforcement: nothing here requires the target engine to be
installed — these are TEXT artifacts the operator can take to the engine.
A future build can attach a real Godot/Blender headless runner when
those are detected READY.
"""
from __future__ import annotations

import json
import logging
import time
from pathlib import Path
from typing import Any, Optional

_log = logging.getLogger(__name__)


def run(kind: str, params: dict) -> dict:
    intent = params.get("intent_text", "")
    spec   = params.get("spec")
    psess  = params.get("session")

    if psess is None:
        return {"outcome": "FAIL", "error": "missing session", "artifacts": []}

    out_dir = Path(psess.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    if kind == "scaffold":
        return _scaffold(intent, spec, psess, out_dir)
    if kind == "design_doc":
        return _design_doc(intent, spec, psess, out_dir)
    if kind == "blender_script":
        return _blender_script(intent, spec, psess, out_dir)
    if kind == "godot_project":
        return _godot_project(intent, spec, psess, out_dir)
    # Default: produce everything we can
    return _scaffold(intent, spec, psess, out_dir)


def _scaffold(intent: str, spec, psess, out_dir: Path) -> dict:
    artifacts: list[str] = []
    errors: list[str] = []

    for fn in (_design_doc, _godot_project, _blender_script):
        try:
            r = fn(intent, spec, psess, out_dir)
            if r.get("outcome") == "OK":
                artifacts.extend(r.get("artifacts", []))
            else:
                errors.append(f"{fn.__name__}: {r.get('error', 'unknown')}")
        except Exception as e:
            errors.append(f"{fn.__name__}: {e}")
    outcome = "OK" if artifacts else "FAIL"
    return {
        "outcome":   outcome,
        "artifacts": artifacts,
        "backend":   "game_scaffold",
        "errors":    errors,
    }


def _design_doc(intent: str, spec, psess, out_dir: Path) -> dict:
    style = getattr(spec, "style", "")    or "open"
    tone  = getattr(spec, "tone",  "")    or "neutral"
    architecture = getattr(spec, "architecture_style", "")    or ""
    lore  = getattr(spec, "world_lore", "")    or ""
    palette = getattr(spec, "color_palette", []) or []
    soundtrack = getattr(spec, "soundtrack_profile", "")    or ""

    name = _project_name(intent)
    doc = f"""# {name}

> {intent or "DBOMBLOCAL game scaffold"}

Generated by DBOMBLOCAL Pyramid Engine on {time.strftime('%Y-%m-%d %H:%M:%S')}.

## Concept

- **Style:** {style}
- **Tone:** {tone}
- **Architecture:** {architecture or "—"}
- **World lore:** {lore or "—"}
- **Soundtrack profile:** {soundtrack or "—"}
- **Color palette:** {' '.join(palette) if palette else "—"}

## Core Loop

1. Operator/player enters the {style or 'world'}.
2. Stakes are introduced via {tone or 'opening'} cinematics.
3. {_loop_mechanic_for(style, tone)}
4. Progression is gated by {_progression_for(tone)}.
5. Climax escalates pacing to {tone}; resolution reflects operator choice.

## Mechanics

{_mechanics_list(style, tone)}

## World Structure

- Region count: 4 zones progressing in difficulty.
- Faction count: 3, with shifting alliances driven by player action.
- Environmental layer: {architecture or 'standard terrain'}; weather drifts per simulation engine.
- Tactical layer: see simcore output for procedural maps + trajectory projection.

## Art Direction

- **Lighting:** {getattr(spec, 'lighting', None) or 'natural'}
- **Composition:** {getattr(spec, 'composition', None) or 'standard'}
- **Atmosphere:** {getattr(spec, 'atmosphere', None) or '—'}

## Audio Direction

{soundtrack or 'Cinematic underscore, layered with diegetic ambient texture.'}

## Production Notes

- This scaffold is a real text artifact, written to the session's output directory.
- Pair with the Godot project files in the same directory to bootstrap a prototype.
- Run the Blender script (`scene.py`) via `blender --python scene.py` to generate
  a placeholder environment matching this spec.
- Soundtrack stems and concept art frames (when generated) are co-located.

— DBOMBLOCAL · session {psess.session_id}
"""
    out_path = out_dir / "GAME_DESIGN.md"
    out_path.write_text(doc, encoding="utf-8")
    _register(psess, out_path, "game_scaffold")
    return {"outcome": "OK", "artifacts": [str(out_path)],
            "backend": "game_scaffold"}


def _godot_project(intent: str, spec, psess, out_dir: Path) -> dict:
    name = _project_name(intent)
    proj_dir = out_dir / "godot_project"
    proj_dir.mkdir(parents=True, exist_ok=True)

    # project.godot
    palette = getattr(spec, "color_palette", []) or []
    bg_hex = palette[0] if palette else "#06091c"
    project_godot = f"""; Godot 4 project file — generated by DBOMBLOCAL
config_version=5

[application]
config/name="{name}"
config/description="{(intent or '')[:200]}"
run/main_scene="res://main.tscn"
config/features=PackedStringArray("4.2", "Forward Plus")

[display]
window/size/viewport_width=1920
window/size/viewport_height=1080

[rendering]
environment/defaults/default_clear_color=Color("{bg_hex}")
"""
    (proj_dir / "project.godot").write_text(project_godot, encoding="utf-8")

    # main.tscn
    main_tscn = """[gd_scene load_steps=2 format=3]

[ext_resource type="Script" path="res://main.gd" id="1"]

[node name="Main" type="Node2D"]
script = ExtResource("1")
"""
    (proj_dir / "main.tscn").write_text(main_tscn, encoding="utf-8")

    # main.gd
    main_gd = f"""extends Node2D
# Generated by DBOMBLOCAL Pyramid Engine.
# Intent: {(intent or '')[:120]}
# Style: {getattr(spec, 'style', None)}, Tone: {getattr(spec, 'tone', None)}

func _ready() -> void:
    print("DBOMBLOCAL scaffold ready · style=", "{getattr(spec, 'style', '') or 'none'}")
    print("Operator intent: ", "{(intent or '')[:120]}")

func _process(delta: float) -> void:
    pass
"""
    (proj_dir / "main.gd").write_text(main_gd, encoding="utf-8")

    # README
    readme = f"""# {name} — Godot 4 Scaffold

Open with Godot 4.2+:
1. `godot --editor --path .`
2. Press F5 to run.

Generated by DBOMBLOCAL on {time.strftime('%Y-%m-%d')}.
"""
    (proj_dir / "README.md").write_text(readme, encoding="utf-8")

    artifacts = [str(p) for p in (
        proj_dir / "project.godot",
        proj_dir / "main.tscn",
        proj_dir / "main.gd",
        proj_dir / "README.md",
    )]
    for ap in artifacts:
        _register(psess, Path(ap), "godot_scaffold")

    return {"outcome": "OK", "artifacts": artifacts,
            "backend": "godot_scaffold"}


def _blender_script(intent: str, spec, psess, out_dir: Path) -> dict:
    name = _project_name(intent)
    palette = getattr(spec, "color_palette", []) or []
    bg = palette[0] if palette else "#06091c"
    architecture = getattr(spec, "architecture_style", "") or ""

    script = f"""# Generated by DBOMBLOCAL — run via `blender --python scene.py`
# Intent: {(intent or '')[:160]}
# Style: {getattr(spec, 'style', None)}  Tone: {getattr(spec, 'tone', None)}
import bpy
import math

def hex_to_rgb(h):
    h = h.lstrip('#')
    return tuple(int(h[i:i+2], 16) / 255.0 for i in (0, 2, 4))

# Clear scene
bpy.ops.object.select_all(action='SELECT')
bpy.ops.object.delete(use_global=False)

# Ground plane
bpy.ops.mesh.primitive_plane_add(size=40)
ground = bpy.context.object
ground.name = "Ground"

# Camera
bpy.ops.object.camera_add(location=(10, -10, 7), rotation=(math.radians(64), 0, math.radians(45)))
bpy.context.scene.camera = bpy.context.object

# Sun
bpy.ops.object.light_add(type='SUN', location=(5, 5, 10))

# Architectural pillars matching style
for i in range(5):
    x = math.cos(i * math.pi * 2 / 5) * 4
    y = math.sin(i * math.pi * 2 / 5) * 4
    bpy.ops.mesh.primitive_cube_add(size=1, location=(x, y, 1.5))
    bpy.context.object.scale.z = 3.0

# Background color
world = bpy.context.scene.world
if world is None:
    world = bpy.data.worlds.new("World")
    bpy.context.scene.world = world
r, g, b = hex_to_rgb("{bg}")
if world.use_nodes:
    bg_node = world.node_tree.nodes.get("Background")
    if bg_node is not None:
        bg_node.inputs[0].default_value = (r, g, b, 1.0)

print(f"DBOMBLOCAL scaffold loaded · intent='{(intent or '')[:60]}' style='{getattr(spec, 'style', '') or 'none'}'")
"""
    out_path = out_dir / "blender_scene.py"
    out_path.write_text(script, encoding="utf-8")
    _register(psess, out_path, "blender_scaffold")
    return {"outcome": "OK", "artifacts": [str(out_path)],
            "backend": "blender_scaffold"}


# ── Helpers ────────────────────────────────────────────────────────────
def _project_name(intent: str) -> str:
    if not intent:
        return "DBOMBLOCAL_Scaffold"
    words = [w for w in intent.replace("/", " ").split() if w.isalnum()][:4]
    return "_".join(words) or "DBOMBLOCAL_Scaffold"


def _loop_mechanic_for(style: str, tone: str) -> str:
    s = (style or "").lower(); t = (tone or "").lower()
    if "cyberpunk" in s or "sci" in s:
        return ("Player executes infiltration loops: gather intel → exploit "
                "vulnerability → escalate → fade. Resource is reputation.")
    if "fantasy" in s:
        return ("Player traverses regions: discover lore → ally with faction → "
                "complete trial → grow power. Resource is renown.")
    if "horror" in s or t in ("dark", "fear"):
        return ("Player survives encounters: scavenge → conceal → escape → "
                "uncover. Resource is sanity.")
    if "noir" in s:
        return ("Player investigates: gather clue → interrogate → deduce → "
                "confront. Resource is leverage.")
    return ("Player explores: observe → act → adapt → master. Resource is "
            "knowledge.")


def _progression_for(tone: str) -> str:
    t = (tone or "").lower()
    if t in ("legendary", "epic", "triumph"):
        return "milestone reveals (3 acts, escalating stakes)"
    if t in ("dark", "intense", "horror"):
        return "discovery of buried lore"
    if t in ("serene", "melancholic"):
        return "introspective moments between regions"
    return "skill checks and operator-chosen branches"


def _mechanics_list(style: str, tone: str) -> str:
    base = [
        "- **Movement:** locomotion + stealth + traversal",
        "- **Interaction:** examine + use + dialogue",
        "- **Combat / Conflict:** kind chosen per encounter (direct or indirect)",
        "- **Inventory:** capped, weight-driven choices",
        "- **Save/Load:** checkpoint at region entry",
    ]
    s = (style or "").lower(); t = (tone or "").lower()
    if "cyberpunk" in s:
        base.append("- **Hacking:** node graph minigame with credentials currency")
    if "fantasy" in s:
        base.append("- **Spellcraft:** elemental affinity + cooldown")
    if "horror" in s or "dark" in t:
        base.append("- **Sanity meter:** decays under sustained tension, recovers in safe zones")
    if "strategy" in s or t in ("legendary", "epic"):
        base.append("- **Tactical map:** entity placement + trajectory plan via simcore")
    return "\n".join(base)


def _register(psess, path: Path, backend: str) -> None:
    try:
        from engine.production_core import get_production_core
        get_production_core().register_artifact(psess, str(path), backend)
    except Exception:
        pass
